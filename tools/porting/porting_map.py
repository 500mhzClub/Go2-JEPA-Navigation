"""Generate docs/PORTING_MAP.md: every original file whose functions ran in the P1 runtime trace, with its target module.

Input: the P1 trace in the frozen snapshot (`$GO2NAV_SNAPSHOT/docs/go2_research_artifact_p1_runtime_trace_2026-10-06.json`).
The target assignment is a first-pass filename heuristic. Entries are refined by hand as modules are ported, and the
`status` column in docs/PORTING_MAP.md is the record. Re-running the tool keeps the existing targets and statuses.

Usage: GO2NAV_SNAPSHOT=/path/to/snapshot python tools/porting/porting_map.py
"""
import json
import os
from pathlib import Path
import re

REPO = Path(__file__).resolve().parents[2]
OUT = REPO/'docs/PORTING_MAP.md'
RULES = [  # (target, pattern on the original path), first match wins
    ('go2nav.mazes', r'lewm_worlds/|maze|_sets_|layout|registry|generate_go2'),
    ('go2nav.locomotion', r'go2_adapter|locomotion|policy_contract'),
    ('go2nav.sim', r'lewm_genesis/|patches|friction|dynamics|physics_session|paired_camera_session|depth_noise|scene|articulated|demo_textured|body_observation|union_wall'),
    ('go2nav.models', r'readout|predictor|dense_horizon|decoder|vjepa|encoder|jepa|c1_adaptive|c1_refit|command_history|motion_controls|frozen_dense'),
    ('go2nav.controllers', r'oracle|reactive|controller_v|short_pulse_navigation_runtime|dense_navigation'),
    ('go2nav.perception', r'pose|tracker|gyro|anchor|registration|floor|rgbd|camera|depth|sensor|observation|visual_motion|causal_sensor'),
    ('go2nav.planning', r'map|frontier|route|routing|connectivity|waypoint|clearance|veto|dispatch|recovery|harness|planning|stopping|pulse|turn|exit|coverage|footprint|support|reserve|margin|pessimistic|multirate|contact'),
    ('go2nav.training', r'fit_|train_|cache|prepare_'),
    ('go2nav.data', r'replay|collect|recording|context'),
    ('go2nav.eval', r'mission|cohort|launch|run_go2|episode|evaluation|closeout|wall|budget|headroom|output|json'),
    ('experiments', r'report|score|summarise|evaluate|count_|analyse|render|probe'),
]


def existing():
    if not OUT.exists():
        return {}
    rows = {}
    for line in OUT.read_text().splitlines():
        cells = [c.strip() for c in line.strip('|').split('|')]
        if len(cells) == 5 and cells[0].startswith('`'):
            rows[cells[0].strip('`')] = (cells[3], cells[4])
    return rows


def main():
    snapshot = Path(os.environ['GO2NAV_SNAPSHOT'])
    trace = json.loads((snapshot/'docs/go2_research_artifact_p1_runtime_trace_2026-10-06.json').read_text())['files']
    keep = existing()
    rows = []
    for path, v in trace.items():
        fns = v['executed_functions']
        if not fns:
            continue
        lines = sum(f['executed'] for f in fns.values())
        target = next((t for t, rule in RULES if re.search(rule, path)), 'unclassified')
        target, status = keep.get(path, (target, 'todo'))
        rows.append((target, -lines, path, len(fns), status))
    rows.sort()
    totals = {}
    for target, neg, *_ in rows:
        totals.setdefault(target, [0, 0])
        totals[target][0] += 1
        totals[target][1] += -neg
    text = ['# Porting map', '',
            'Every original LeWMQuad-v3 file with executed function bodies in the P1 runtime trace (missions C0–C4, C1A and C1R;',
            'recovery on and off; friction; marked patches; forecast degradation; calibrated margins; the offline reports and fits),',
            'with its target module and porting status. Generated by `tools/porting/porting_map.py`, which keeps existing targets and',
            'statuses on re-run. Files outside the trace (training lineage, data collection, maze generation, rendering) are listed in',
            '[MIGRATION_STATUS.md](MIGRATION_STATUS.md).', '',
            '| Target | Files | Executed lines |', '|---|---:|---:|']
    text += [f'| `{t}` | {n} | {l} |' for t, (n, l) in sorted(totals.items())]
    text += ['', '| Original file | Executed lines | Functions | Target | Status |', '|---|---:|---:|---|---|']
    text += [f'| `{p}` | {-neg} | {n} | {t} | {s} |' for t, neg, p, n, s in rows]
    OUT.write_text('\n'.join(text)+'\n')
    print({t: v for t, v in sorted(totals.items())})


if __name__ == '__main__':
    main()
