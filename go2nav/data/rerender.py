"""Regenerate a recorded mission's camera frames by replaying its executed commands (verified replay).

    python -m go2nav.data.rerender RUN_DIR OUT_DIR [--auxiliary] [--depth]

Missions keep only frame hashes. The frames used for training are regenerated by replaying the run's requested
commands, open loop, through the simulator: physics depends only on the commands, so no controller (and no harness
version) is needed. Every physics sample is checked against the run's trace and every frame against its recorded
pixel hashes, so a regenerated frame is exactly the one the controller saw. Works for original runs (dev_run.json,
launch_pin.json) and for runs of this repository (config.json).

Output: OUT_DIR/ego_frames/NNNN.png (primary RGB); with --auxiliary, auxiliary_frames/NNNN.png; with --depth,
depth/NNNN.npz (both cameras' native depth).
"""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
from PIL import Image

TRACE_FIELDS = ('timestamp_s', 'base_pose_world', 'base_twist_world', 'joint_position', 'joint_velocity', 'applied_command')


def load(run, name):
    return json.loads((Path(run)/name).read_text())


def run_dynamics(run):
    """The run's Dynamics (friction, strips, stall stop) from either record format."""
    from go2nav.sim.dynamics import Dynamics
    run = Path(run)
    config = load(run, 'config.json')
    record = config.get('dynamics') if 'arm' in config else None
    if record is None and (run/'launch_pin.json').exists():
        record = load(run, 'launch_pin.json').get('dynamics')
    if not record:
        return None
    dynamics = Dynamics(stall_stop_s=record.get('recording_stall_stop_s'))
    if record.get('perturbation') == 'uniform_floor_friction':
        dynamics.friction_mu = record['mu']
    elif record.get('perturbation') in ('low_friction_patches', 'low_friction_strips'):
        placement = record['placement']
        dynamics.strips = [s['rect'] for s in placement.get('strips', placement.get('patches', []))]
        dynamics.strip_mu, dynamics.marked = record['mu'], bool(record['marked'])
    return dynamics


def run_demo_textures(run):
    """Whether the run drew the demonstration surfaces (`go2nav.sim.demo_appearance`)."""
    run = Path(run)
    config = load(run, 'config.json')
    if 'arm' in config:
        return bool(config.get('demo_textures'))
    record = load(run, 'dev_run.json') if (run/'dev_run.json').exists() else {}
    return bool((record.get('dynamics') or {}).get('demo_textures'))


def recorded_hashes(run):
    """{frame: {'primary': sha256, 'auxiliary': sha256}} of the frames' RGB, when the run recorded them."""
    path = Path(run)/'native/in_memory_camera_observations.json'
    if not path.exists():
        return {}
    out = {}
    for row in load(run, 'native/in_memory_camera_observations.json')['frames']:
        pixels = row.get('pixel_sha256')
        if isinstance(pixels, str):
            pixels = json.loads(pixels.replace("'", '"'))
        if pixels:
            out[row['frame']] = {camera: pixels[camera]['rgb_sha256'] for camera in ('primary', 'auxiliary')}
    return out


def replay(run, out, *, auxiliary=False, depth=False):
    """Replay a run and write its frames (see the module docstring). Returns the number of frames written."""
    from go2nav import artifacts
    from go2nav.sim import scene
    from go2nav.sim.session import MissionSession, PhysicalStop
    run, out = Path(run), Path(out)
    spec, requests, acquisitions = load(run, 'specification.json'), load(run, 'requests.json'), load(run, 'acquisitions.json')
    with np.load(run/'native/physics_trace.npz') as archive:
        trace = {key: archive[key].copy() for key in TRACE_FIELDS}
    hashes = recorded_hashes(run)
    folders = dict(primary=out/'ego_frames', auxiliary=out/'auxiliary_frames' if auxiliary else None, depth=out/'depth' if depth else None)
    for folder in folders.values():
        if folder is not None:
            folder.mkdir(parents=True, exist_ok=True)
    scene.init_genesis(spec['procedural_seed'])
    session = MissionSession(spec, out/'visual_meshes', policy_checkpoint=artifacts.path('go2_locomotion_policy'),
                             dynamics=run_dynamics(run), demo_textures=run_demo_textures(run))
    session.settle()
    checked = check_samples(session, trace, 0)

    def take_frame():
        frame = session.frames
        policy, primary_depth, _, auxiliary_depth, auxiliary_rgb, _ = session.frame()
        images = dict(primary=policy['image']['rgb'], auxiliary=auxiliary_rgb['rgb'])
        for camera, expected in hashes.get(frame, {}).items():
            if hashlib.sha256(images[camera].tobytes()).hexdigest() != expected:
                raise ValueError(f'frame {frame} {camera} RGB differs from the recording')
        Image.fromarray(images['primary']).save(folders['primary']/f'{frame:04d}.png')
        if folders['auxiliary'] is not None:
            Image.fromarray(images['auxiliary']).save(folders['auxiliary']/f'{frame:04d}.png')
        if folders['depth'] is not None:
            np.savez_compressed(folders['depth']/f'{frame:04d}.npz', primary=session.last_native_depth[0],
                                auxiliary=session.last_native_depth[1])
    for tick, row in enumerate(requests):
        if tick % 5 == 0:
            take_frame()
        session.phase = 2
        try:
            session.step(row['requested_command'])
        except PhysicalStop:
            if 'applied_command' in row:
                raise
            break
        checked = check_samples(session, trace, checked)
    while session.frames < len(acquisitions):  # a frame acquired after the last request (a failure on that frame)
        take_frame()
    return session.frames


def check_samples(session, trace, start):
    """Compare the session's physics samples from `start` with the trace; returns the new count."""
    for i in range(start, len(session.samples)):
        if i >= len(trace['timestamp_s']):
            raise ValueError(f'replay ran past the recorded trace at sample {i}')
        for key in TRACE_FIELDS:
            if not np.array_equal(np.asarray(session.samples[i][key]), trace[key][i]):
                raise ValueError(f'physics sample {i} {key} differs from the recording')
    return len(session.samples)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('run', type=Path)
    p.add_argument('out', type=Path)
    p.add_argument('--auxiliary', action='store_true')
    p.add_argument('--depth', action='store_true')
    a = p.parse_args()
    print(json.dumps(dict(run=str(a.run), frames=replay(a.run, a.out, auxiliary=a.auxiliary, depth=a.depth))))


if __name__ == '__main__':
    main()
