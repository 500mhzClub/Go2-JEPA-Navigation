"""The ring world's corpus (docs/dynamic/PLAN.md P20 item 4): episodes in the kinematic world, observed through the
range ring alone, with commands that are not scripted from privileged state.

    python -m go2nav.data.ring_corpus build --mazes-root ROOT --out OUT [--episodes 5000] [--val 500] [--workers N]
    python -m go2nav.data.ring_corpus summary OUT
    python -m go2nav.data.ring_corpus pack OUT

`pack` writes each split as contiguous arrays for training (P21): OUT/packed/<split>_<name>.npy for `ranges`
(N, 720) float16, `requested` and `pose` (N, 3) float32, and `starts` (episodes + 1,): where each episode begins.

**Mazes:** the world model's corpus layouts (`lewm_sets_v1`, generated by `data.lewm_corpus` under ROOT/mazes): train
episodes on layouts 0-1199, validation on 1200-1299, so the two share no topology and neither shares one with an
evaluation set. The plan named a new set of 200 validation-family layouts; these are used instead, because the 4 x 4
family has few topologies left and the Genesis corpus is on these, which P23 needs.

**An episode** (`EPISODE_S`, 120 s): a layout and home pose drawn at random, 0 to 4 walkers (`COUNTS`), all of one
kind drawn from polite, not yielding and reactive, placed as missions place them (`sim.obstacles.place_obstacles`).
The robot walks to cells drawn at random, each until it is within `REACHED_M` or `GIVE_UP_S` passes, under P17's
planner (`planning.sampling`, 1.6 s, the `walkers` terminal distance) with the `ring_frozen` model, so it knows the
walkers only from the ring. At one plan in `INTERVENE` it instead executes a random tape for 0.4 to 2 s, whatever it
leads to with the walkers: knots every `KNOT_S` drawn uniformly within the continuous block's bounds, or (one in
`HOLDS`) a hold. Only the walls are kept out of it: a tape is drawn again (up to `DRAWS` times, else a hold) until the
body's path keeps the planner's floor from the walls, which are known; without this most episodes ended against a wall
within a minute. A contact ends the episode: about half do, mostly against a walker, so an episode averages about
780 frames and the first build is 5,000 episodes, where the plan said 3,000 of 1,200 frames, for the same 3.6
million frames.

**Per episode,** OUT/<split>/<index>.npz, per frame t (the state before the frame's step, then what it did):
- `ranges` (T, 720) float16: the scan, 0 where a beam gave no valid return;
- `pose` (T, 3): x, y, yaw; `requested`, `executed` (T, 3): the frame's command and what the robot made of it;
- `intervention` (T,): the frame's command came from a random tape;
- labels, for measures only (never a model's input): `walkers_xy`, `walkers_velocity` (T, 4, 2; NaN where there is
  no walker), `waiting` (T, 4): the walker is held up by the robot (`sim.kinematic.waiting_on`), `in_sight` (T, 4):
  in the sensor's line of sight;
and OUT/<split>/<index>.json: the layout, home pose, walkers' kind and placement, frames, contact.
"""
import argparse
from concurrent.futures import ProcessPoolExecutor
import json
import multiprocessing
import os
from pathlib import Path

import numpy as np

SEED = 2026111101
EPISODE_S, KNOT_S, REACHED_M, GIVE_UP_S = 120., .4, .3, 40.
INTERVENE, HOLDS, TAPE_S, DRAWS = 4, 5, (.4, 2.), 20
COUNTS, COUNT_P = (0, 1, 2, 3, 4), (.1, .25, .25, .2, .2)
KINDS = ('polite', 'rude', 'reactive')
TRAIN_LAYOUTS, VAL_LAYOUTS = range(0, 1200), range(1200, 1300)
MAX_WALKERS = 4
SET = 'lewm_sets_v1'


def random_tape(rng, frames, start, fields):
    """A random tape (frames, 3) of requests: linear between knots `KNOT_S` apart, drawn within the bounds, keeping
    the walls' floor from `start` (xy, yaw, executed); or a hold."""
    from go2nav.locomotion.safety import BLOCKS
    from go2nav.planning.sampling import FLOOR_M, integrate
    from go2nav.sim.kinematic import FRAME_S, body_points
    hold = np.zeros((frames, 3), np.float32)
    if rng.integers(HOLDS) == 0:
        return hold
    lower, upper, _ = BLOCKS['continuous']
    every = int(round(KNOT_S/FRAME_S))
    knots, steps = np.arange(0, frames+every, every), np.arange(frames)
    for _ in range(DRAWS):
        values = rng.uniform(lower, upper, size=(len(knots), 3))
        tape = np.stack([np.interp(steps, knots, values[:, a]) for a in range(3)], 1).astype(np.float32)
        xy, yaw = integrate(start, tape[None])
        if fields.wall_clearance(body_points(xy, yaw)).min() >= FLOOR_M:
            return tape
    return hold


def episode(mazes_root, index, split):
    """One episode's arrays and record (see the module docstring)."""
    from go2nav.eval.mission import episode_spec
    from go2nav.perception.ring_walkers import mount_of
    from go2nav.planning.sampling import REPLAN_FRAMES, Planner
    from go2nav.sim import kinematic as kin
    from go2nav.sim import obstacles as moving
    rng = np.random.default_rng([SEED, index, split == 'val'])
    layouts = VAL_LAYOUTS if split == 'val' else TRAIN_LAYOUTS
    maze, home = int(rng.choice(layouts)), int(rng.integers(2))
    spec, record = episode_spec(SET, maze, home, root=Path(mazes_root))
    count, kind = int(rng.choice(COUNTS, p=COUNT_P)), str(rng.choice(KINDS))
    placement = []
    while count:
        try:
            placement = moving.place_obstacles(spec, record, count, int(rng.integers(2**62)), polite=kind != 'rude',
                                               reactive=kind == 'reactive')
            break
        except ValueError:
            count -= 1
    world = kin.World(spec, record['home_se2_world'], placement)
    planner = Planner(world.geometry, horizon_s=1.6, terminal='walkers', model='ring_frozen', seed=int(rng.integers(2**31)))
    cells = list(planner.cells.values())
    frames = int(round(EPISODE_S/kin.FRAME_S))
    out = dict(ranges=np.zeros((frames, 720), np.float16), pose=np.zeros((frames, 3), np.float32),
               requested=np.zeros((frames, 3), np.float32), executed=np.zeros((frames, 3), np.float32),
               intervention=np.zeros(frames, bool), walkers_xy=np.full((frames, MAX_WALKERS, 2), np.nan, np.float32),
               walkers_velocity=np.full((frames, MAX_WALKERS, 2), np.nan, np.float32),
               waiting=np.zeros((frames, MAX_WALKERS), bool), in_sight=np.zeros((frames, MAX_WALKERS), bool))
    target, since, queue, random_queue = None, 0, [], False
    targets = interventions = 0
    t = 0
    for t in range(frames):
        scan = world.scan()
        planner.model.observe(t*kin.FRAME_S, scan, world.xy, world.yaw, world.geometry)
        if target is None or np.linalg.norm(world.xy-target) < REACHED_M or (t-since)*kin.FRAME_S > GIVE_UP_S:
            options = [c for c in cells if np.linalg.norm(c-world.xy) > 2*REACHED_M] or cells
            target, since, queue, targets = options[int(rng.integers(len(options)))], t, [], targets+1
        if not queue:
            random_queue = rng.integers(INTERVENE) == 0
            if random_queue:
                start = dict(xy=world.xy, yaw=world.yaw, executed=world.executed)
                tape = random_tape(rng, int(round(rng.uniform(*TAPE_S)/kin.FRAME_S)), start, planner.fields)
                queue, interventions = list(tape), interventions+1
                planner.previous = None
            else:
                queue = list(planner.plan(world.snapshot(), target)[0][:REPLAN_FRAMES])
        requested = queue.pop(0)
        n = len(world.walkers)
        origin = mount_of(world.xy, world.yaw)
        out['ranges'][t], out['pose'][t] = scan[0], (*world.xy, world.yaw)
        out['requested'][t], out['intervention'][t] = requested, random_queue
        if n:
            out['walkers_xy'][t, :n], out['walkers_velocity'][t, :n] = world.walkers_xy(), world.walkers_velocity
            out['waiting'][t, :n] = [kin.waiting_on(w, world.xy) for w in world.walkers]
            out['in_sight'][t, :n] = [world.geometry.visible(origin, xy) for xy in world.walkers_xy()]
        out['executed'][t] = world.step(requested)
        if world.contact is not None:
            break
    used = t+1
    arrays = {k: v[:used] for k, v in out.items()}
    meta = dict(schema='go2nav_ring_corpus.v1', index=index, split=split, set=SET, maze=maze, home_episode=home,
                kind=kind if placement else 'none', walkers=len(placement), placement=placement, frames=used,
                contact=world.contact, targets=targets, interventions=interventions, path_m=round(world.path_m, 2))
    return arrays, meta


def _job(args):
    mazes_root, out, index, split = args
    target = Path(out)/split/f'{index:05d}.npz'
    if target.exists() and target.with_suffix('.json').exists():
        return json.loads(target.with_suffix('.json').read_text())
    os.environ.setdefault('OMP_NUM_THREADS', '1')
    arrays, meta = episode(mazes_root, index, split)
    partial = target.with_name(target.stem+'.tmp.npz')
    np.savez_compressed(partial, **arrays)
    partial.rename(target)
    target.with_suffix('.json').write_text(json.dumps(meta)+'\n')
    return meta


def build(mazes_root, out, *, episodes=5000, val=500, workers=None):
    out = Path(out)
    for split in ('train', 'val'):
        (out/split).mkdir(parents=True, exist_ok=True)
    jobs = [(str(mazes_root), str(out), k, 'val') for k in range(val)] + \
           [(str(mazes_root), str(out), k, 'train') for k in range(episodes-val)]
    with ProcessPoolExecutor(workers or os.cpu_count(), mp_context=multiprocessing.get_context('forkserver')) as pool:
        metas = list(pool.map(_job, jobs, chunksize=2))
    report = summary(out)
    (out/'summary.json').write_text(json.dumps(report, indent=1)+'\n')
    return report


def summary(out):
    """The corpus's contents per split: episodes and frames, frames with a walker in sight, inside an intervention,
    with a walker waiting on the robot, and contacts."""
    out, report = Path(out), {}
    for split in ('train', 'val'):
        metas = [json.loads(p.read_text()) for p in sorted((out/split).glob('*.json'))]
        frames = sight = random = waiting = 0
        for meta in metas:
            with np.load(out/split/f"{meta['index']:05d}.npz") as data:
                frames += len(data['pose'])
                sight += int(data['in_sight'].any(1).sum())
                random += int(data['intervention'].sum())
                waiting += int(data['waiting'].any(1).sum())
        report[split] = dict(episodes=len(metas), frames=frames, walker_in_sight=sight, intervention=random,
                             walker_waiting=waiting, contacts={c: sum(m['contact'] == c for m in metas) for c in ('wall', 'walker')},
                             kinds={k: sum(m['kind'] == k for m in metas) for k in KINDS+('none',)})
    return report


def _load(path):
    with np.load(path) as data:
        return data['ranges'], data['requested'], data['pose']


def pack(out, workers=None):
    """See the module docstring. Returns the frames per split."""
    out = Path(out)
    (out/'packed').mkdir(exist_ok=True)
    sizes = {}
    for split in ('train', 'val'):
        files = sorted((out/split).glob('*.npz'))
        lengths = [json.loads(f.with_suffix('.json').read_text())['frames'] for f in files]
        starts = np.concatenate(([0], np.cumsum(lengths))).astype(np.int64)
        arrays = {name: np.lib.format.open_memmap(out/'packed'/f'{split}_{name}.npy', mode='w+', dtype=dtype,
                                                   shape=(int(starts[-1]), *shape))
                  for name, dtype, shape in (('ranges', np.float16, (720,)), ('requested', np.float32, (3,)),
                                             ('pose', np.float32, (3,)))}
        with ProcessPoolExecutor(workers or os.cpu_count()) as pool:
            for k, (ranges, requested, pose) in enumerate(pool.map(_load, files, chunksize=16)):
                a, b = starts[k], starts[k+1]
                arrays['ranges'][a:b], arrays['requested'][a:b], arrays['pose'][a:b] = ranges, requested, pose
        for array in arrays.values():
            array.flush()
        np.save(out/'packed'/f'{split}_starts.npy', starts)
        sizes[split] = int(starts[-1])
    return sizes


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest='command', required=True)
    b = sub.add_parser('build')
    b.add_argument('--mazes-root', required=True, type=Path, help='the folder holding lewm_sets_v1')
    b.add_argument('--out', required=True, type=Path)
    b.add_argument('--episodes', type=int, default=5000)
    b.add_argument('--val', type=int, default=500)
    b.add_argument('--workers', type=int)
    s = sub.add_parser('summary')
    s.add_argument('out', type=Path)
    k = sub.add_parser('pack')
    k.add_argument('out', type=Path)
    a = p.parse_args()
    if a.command == 'pack':
        print(json.dumps(pack(a.out)))
        return
    if a.command == 'summary':
        print(json.dumps(summary(a.out), indent=1))
        return
    print(json.dumps(build(a.mazes_root, a.out, episodes=a.episodes, val=a.val, workers=a.workers), indent=1))


if __name__ == '__main__':
    main()
